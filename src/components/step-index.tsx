function Figure({ n, tx = 0 }: { n: number; tx?: number }) {
  const d = FIGURE[n];
  if (!d) return null;
  return <path d={d} transform={tx ? `translate(${tx} 0)` : undefined} />;
}

export function StepIndexMark({
  n,
  className,
  ...rest
}: { n: number } & SVGProps<SVGSVGElement>) {
  const clamped = Math.max(1, Math.min(12, Math.round(n)));
  const tens = Math.floor(clamped / 10);
  const ones = clamped % 10;

  return (
    <svg
      {...BOX}
      className={['slm-step-index', className].filter(Boolean).join(' ')}
      fillRule="evenodd"
      clipRule="evenodd"
      {...rest}
    >
      {tens === 0 ? (
        <Figure n={ones} />
      ) : (
        <g transform="translate(0 0) scale(0.78 1) translate(-1.1 0)">
          <Figure n={tens} tx={-0.4} />
          <Figure n={ones} tx={9.6} />
        </g>
      )}
    </svg>
  );
}
